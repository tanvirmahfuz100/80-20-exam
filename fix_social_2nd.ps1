$confidenceIds = @{23 = $true; 102 = $true; 544 = $true}

Write-Output "Starting fixes..."
$totalSuffixApplied = 0
$totalSuffixSkipped = 0
$totalConfidenceAdded = 0
$totalConfidenceSkipped = 0

$utf8NoBom = [System.Text.UTF8Encoding]::new($false)

Get-ChildItem -LiteralPath $baseDir -Filter "chapter_*.json" | Sort-Object Name | ForEach-Object {
    $filePath = $_.FullName
    Write-Output ("`nProcessing " + $_.Name + "...")
    
    $json = Get-Content -LiteralPath $filePath -Raw -Encoding UTF8 | ConvertFrom-Json
    $modified = $false
    
    foreach ($q in $json) {
        $qid = [int]$q.id
        
        # 1. Append college/board suffix
        if ($suffixMap.ContainsKey($qid)) {
            $suffix = $suffixMap[$qid]
            if (-not $q.question.EndsWith($suffix)) {
                $q.question = $q.question + ' ' + $suffix
                $totalSuffixApplied++
                $modified = $true
                Write-Output ("  Q${qid}: Appended suffix")
            } else {
                $totalSuffixSkipped++
                Write-Output ("  Q${qid}: Suffix already present, skipped")
            }
        }
        
        # 2. Add/update confidence=low
        if ($confidenceIds.ContainsKey($qid)) {
            $hasProp = ($q.PSObject.Properties.Name -contains "confidence")
            if (-not $hasProp) {
                $q | Add-Member -NotePropertyName "confidence" -NotePropertyValue "low"
                $totalConfidenceAdded++
                $modified = $true
                Write-Output ("  Q${qid}: Added confidence=low")
            } elseif ($q.confidence -ne "low") {
                $q.confidence = "low"
                $totalConfidenceAdded++
                $modified = $true
                Write-Output ("  Q${qid}: Updated confidence=low")
            } else {
                $totalConfidenceSkipped++
                Write-Output ("  Q${qid}: Already has confidence=low, skipped")
            }
        }
    }
    
    if ($modified) {
        $newJson = $json | ConvertTo-Json -Depth 10
        [System.IO.File]::WriteAllText($filePath, $newJson, $utf8NoBom)
        Write-Output ("  -> Saved " + $_.Name)
    } else {
        Write-Output ("  -> No changes needed")
    }
}

